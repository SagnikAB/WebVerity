"""Evidence aggregator and result consolidation module."""

from typing import Any

from backend.app.detection.risk_scoring import calculate_risk_score
from backend.app.schemas.evidence import Finding
from backend.app.schemas.scan import ThreatAssessment


class AggregatedScanResult:
    """Aggregated representation of all module results, findings, and threat scoring."""

    def __init__(
        self,
        modules: dict[str, Any],
        findings: list[Finding],
        threat_assessment: ThreatAssessment,
        statuses: dict[str, str],
    ):
        self.modules = modules
        self.findings = findings
        self.threat_assessment = threat_assessment
        self.statuses = statuses


def aggregate_evidence(
    url_result: dict[str, Any],
    url_findings: list[Finding],
    dns_result: dict[str, Any],
    dns_findings: list[Finding],
    tls_result: dict[str, Any],
    tls_findings: list[Finding],
) -> AggregatedScanResult:
    """Aggregate individual analyzer outputs into a cohesive assessment.

    Args:
        url_result: URL feature analysis dictionary.
        url_findings: Findings generated by URL analysis.
        dns_result: DNS query result dictionary.
        dns_findings: Findings generated by DNS analysis.
        tls_result: TLS certificate analysis dictionary.
        tls_findings: Findings generated by TLS inspection.

    Returns:
        AggregatedScanResult instance.
    """
    raw_findings = url_findings + dns_findings + tls_findings

    # Deduplicate findings while preserving order
    deduplicated_findings: list[Finding] = []
    seen_ids = set()
    for f in raw_findings:
        if f.id not in seen_ids:
            seen_ids.add(f.id)
            deduplicated_findings.append(f)

    # Track module execution statuses
    statuses = {
        "url_analysis": url_result.get("status", "COMPLETED"),
        "dns_analysis": dns_result.get("dns_status", "UNKNOWN"),
        "tls_analysis": tls_result.get("status", "UNKNOWN"),
    }

    modules = {
        "url_analysis": url_result,
        "dns_analysis": dns_result,
        "tls_analysis": tls_result,
    }

    threat_assessment = calculate_risk_score(
        findings=deduplicated_findings,
        module_statuses=statuses,
    )

    return AggregatedScanResult(
        modules=modules,
        findings=deduplicated_findings,
        threat_assessment=threat_assessment,
        statuses=statuses,
    )
